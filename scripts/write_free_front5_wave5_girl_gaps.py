def validate() -> None:
    for sid, st in STORIES.items():
        assert st["companion"] == "girl", sid
        assert len(st["pages"]) == 12 and len(st["bubbles"]) == 12 and len(st["scenes"]) == 12
        for i, page in enumerate(st["pages"], 1):
            w = len(page.split())
            if not (5 <= w <= 28):
                raise SystemExit(f"bad word count {sid} {i}: {w} — {page}")
            for L, R in st["bubbles"]:
                if len(L) > 22 or len(R) > 22:
                    raise SystemExit(f"bubble too long {sid}: {L!r} {R!r}")
        print(f"{sid} OK companion=girl")


